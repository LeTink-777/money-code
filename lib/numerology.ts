/** Digit sum of the birth date, reduced to a single digit 1–9. */
export function moneyCode(iso: string): number | null {
  const digits = iso.replace(/\D/g, "");
  if (digits.length !== 8) return null;

  let sum = digits.split("").reduce((acc, digit) => acc + Number(digit), 0);
  while (sum > 9) {
    sum = String(sum)
      .split("")
      .reduce((acc, digit) => acc + Number(digit), 0);
  }
  return sum === 0 ? 9 : sum;
}

